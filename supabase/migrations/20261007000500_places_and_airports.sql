-- air only above 12 h) and to suggest the nearest airports for towns without one.

alter table public.settings
  add column if not exists surface_speed_kmph numeric(5,1) not null default 50 check (surface_speed_kmph > 0),
  add column if not exists road_factor        numeric(4,2) not null default 1.3 check (road_factor >= 1);

create table if not exists public.places (
  name  text primary key check (name = lower(btrim(name)) and name <> ''),
  lat   double precision not null check (lat between -90 and 90),
  lon   double precision not null check (lon between -180 and 180),
  state text not null default ''
);

create table if not exists public.airports (
  iata text primary key check (iata ~ '^[A-Z]{3}$'),
  name text not null,
  lat  double precision not null check (lat between -90 and 90),
  lon  double precision not null check (lon between -180 and 180)
);

